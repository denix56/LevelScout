-- tools/import/writer.lua: writes the baked ForeverDB layer as addon data files (LevelScout/data/*.lua).

local W = {}

local function notice(build, generated)
    return table.concat({
        "-- Data: ForeverDB.net (https://foreverdb.net), build " .. build .. ". Reuse requires this credit: see NOTICE.txt (GPL-3.0 section 7(b)).",
        "-- Includes CMaNGOS classic-db data (https://github.com/cmangos/classic-db, GPL-3.0) via ForeverDB. QuestieDB is read",
        "-- at runtime from the installed QuestieDB addon, not stored here. Part of LevelScout, GPL-3.0; see LICENSE and CREDITS.md.",
        "-- Generated by tools/import/import.lua on " .. generated .. ". Do not edit by hand; re-run the import instead.",
        "local _, ns = ...",
        "ns.data = ns.data or {}",
        "ns.data.fdb = ns.data.fdb or {}",
        "",
    }, "\n")
end

local function sortedKeys(t)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys, function(a, b)
        local ta, tb = type(a), type(b)
        if ta ~= tb then return ta == "number" end
        return a < b
    end)
    return keys
end

local function keyOf(k, literal)
    return (type(k) == "string" and k:match("^[%a_][%w_]*$")) and k or ("[" .. literal(k) .. "]")
end

-- A Lua literal. Tables are written over several indented lines; with `inline`, on one line.
local function literal(v, indent, inline)
    local t = type(v)
    if t == "string" then return string.format("%q", v) end
    if t == "number" then
        if v == math.floor(v) and math.abs(v) < 2 ^ 53 then return string.format("%d", v) end
        return string.format("%.14g", v)
    end
    if t == "boolean" then return tostring(v) end
    if t ~= "table" then error("cannot write a " .. t) end
    indent = indent or ""
    local inner = inline and "" or (indent .. "  ")
    local parts = {}
    local n = 0 -- length of the gap-free array part (#v is undefined for tables with holes)
    while v[n + 1] ~= nil do n = n + 1 end
    for i = 1, n do parts[#parts + 1] = inner .. literal(v[i], inner, inline) end
    for _, k in ipairs(sortedKeys(v)) do
        if not (type(k) == "number" and k >= 1 and k <= n and k == math.floor(k)) then
            parts[#parts + 1] = inner .. keyOf(k, literal) .. (inline and "=" or " = ") .. literal(v[k], inner, inline)
        end
    end
    if #parts == 0 then return "{}" end
    if inline then return "{" .. table.concat(parts, ",") .. "}" end
    return "{\n" .. table.concat(parts, ",\n") .. ",\n" .. indent .. "}"
end
W.literal = literal

--- `ns.data.fdb.<name> = { [id] = value, ... }`, one entry per line (table values on that line).
local function idTable(name, t)
    local lines = { "ns.data.fdb." .. name .. " = {" }
    for _, k in ipairs(sortedKeys(t)) do
        local v = t[k]
        if v then lines[#lines + 1] = "[" .. literal(k) .. "]=" .. literal(v, "", true) .. "," end
    end
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n")
end

local function writeFile(dir, name, body, out)
    local path = dir .. "/" .. name
    local f = assert(io.open(path, "wb"))
    f:write(body, "\n")
    f:close()
    out[#out + 1] = { name = name, bytes = #body + 1 }
    -- Every generated file must compile under Lua 5.1 (constant limits, quoting).
    assert(loadstring(body, "@" .. path), "generated file does not compile: " .. path)
end

-- Which ForeverDB tables go into which file (LevelScout.toc lists the files).
W.FILES = {
    { "Quests.lua", { "qcQuests", "qfQuests", "qcGone", "qcExcl", "questXP", "qobj", "groupSize", "startMap" } },
    { "QuestSpots.lua", { "qfPoi", "qfSeen", "qfArea" } },
    { "Npcs.lua", { "qcNpc", "qfNpcNames", "qfNpcSpots", "npcLv", "npcSpot" } },
    { "Objects.lua", { "qcObj" } },
    { "Items.lua", { "qfItems", "qdrop", "qcItem" } },
}

function W.Write(dir, model)
    os.execute(string.format("mkdir -p %q", dir))
    local head = notice(model.meta.build, model.meta.generated)
    local out = {}
    writeFile(dir, "Meta.lua", head .. "ns.data.meta = " .. literal(model.meta), out)
    local written = {}
    for _, file in ipairs(W.FILES) do
        local bodies = {}
        for _, name in ipairs(file[2]) do
            if type(model.fdb[name]) ~= "table" then error("writer: no table " .. name) end
            bodies[#bodies + 1] = idTable(name, model.fdb[name])
            written[name] = true
        end
        writeFile(dir, file[1], head .. table.concat(bodies, "\n"), out)
    end
    writeFile(dir, "World.lua", head .. "ns.data.fdb.dungeons = " .. literal(model.fdb.dungeons) .. "\n"
        .. "ns.data.world = " .. literal(model.world), out)
    written.dungeons = true
    for name in pairs(model.fdb) do
        if not written[name] then error("writer: table " .. name .. " has no file") end
    end
    return out
end

return W
